tr <- function(key, language = "en", ...) {
  language <- if (language %in% names(translations)) language else "en"
  value <- unname(translations[[language]][[key]])
  if (is.null(value) || is.na(value)) value <- key
  arguments <- list(...)
  if (length(arguments) > 0) do.call(sprintf, c(list(value), arguments)) else value
}
